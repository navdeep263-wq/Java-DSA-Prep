public class Escape {
    public static void main(String[] args) {
        
        //Right half pyramid using escape sequences
        System.out.println("*\n**\n***\n****\n*****");
        //left half pyramid using escape sequences
        System.out.println("    *\n   **\n  ***\n ****\n*****");
        //Reverse right half pyramid using escape sequences
        System.out.println("*****\n****\n***\n**\n*");
    }
}
